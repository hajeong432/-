# -*- coding: utf-8 -*-
import datetime

def 우산_체크(현재_기온, 강수_확률, 하늘_상태):
    print(f"\n📅 분석 시각: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M')}")
    print(f"🌡️ 현재 기온: {현재_기온}°C")
    print(f"🌧️ 강수 확률: {강수_확률}%")
    print(f"☁️ 하늘 상태: {하늘_상태}")
    print("-" * 40)
    
    # 우산 휴대 여부 결정 로직
    if 강수_확률 >= 60 or "비" in 하늘_상태:
        return "📢 [결과] 오늘은 무조건 '장우산'을 챙기세요! 비가 올 확률이 매우 높습니다."
    elif 30 <= 강수_확률 < 60:
        return "📢 [결과] '접이식 우산'을 가방에 넣으세요. 혹시 모를 소나기에 대비합시다."
    elif "눈" in 하늘_상태:
        return "📢 [결과] 비 대신 눈이 오네요! 우산이나 모자를 챙기세요."
    else:
        return "✅ [결과] 오늘은 우산 없이 가볍게 외출하셔도 좋습니다!"

def 실행():
    print("🌤️ 실시간 날씨 기반 우산 알리미 (시뮬레이션)")
    print("=" * 45)
    
    # 1. 실제로는 여기서 API를 통해 날씨를 가져옵니다.
    # 지금은 테스트를 위해 가상의 실시간 데이터를 넣었습니다.
    테스트_기온 = 12
    테스트_강수확률 = 45  # 이 수치를 바꿔보며 테스트해보세요!
    테스트_하늘 = "구름 많음"
    
    결과 = 우산_체크(테스트_기온, 테스트_강수확률, 테스트_하늘)
    print(결과)
    print("=" * 45)

if __name__ == "__main__":
    실행()